// Единый источник правды для того, пришло ли сообщение чата заказа от
// персонала (staff/admin/owner/deputy) или от гостя. У всех ролей персонала
// одинаковые права на управление заказом (см. order.txt), поэтому клиенту
// достаточно отличать "не user" от "user" — специальной обработки по
// конкретной роли персонала не требуется.
class SenderRole {
  static bool isStaff(String senderRole) => senderRole != 'user';
}
